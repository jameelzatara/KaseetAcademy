/* ── shared types ─────────────────────────────────────────────── */

export interface StationItem {
  n: string;
  phase: number;
  title: string;
  sub: string;
  chips: readonly string[];
  project: string;
  hours?: string;
  badge?: string;
  note?: string;
  standalone?: boolean;
  optional?: boolean;
  hot?: boolean;
  ref?: string;
}

export interface PhaseBand {
  from: number;
  to: number;
  label: string;
  sub: string;
  color: string;
}

export interface PortfolioItem {
  n: string;
  title: string;
  kind: string;
  /** output type label (فيديو/وثيقة/صوت/إنتاج كامل) — replaces wave when set */
  outputType?: string;
  hot: boolean;
}

export interface OutcomeItem {
  n: string;
  title: string;
  desc: string;
}

export interface TrainerInfo {
  name: string;
  role: string;
  bio: string;
  chips: string[];
  imgSrc: string;
  imgPosition?: string;
  tag?: string;
}

export interface AdvisorInfo {
  name: string;
  role: string;
  bio: string;
  phone: string;
  waLabel: string;
  imageSrc: string;
}

export interface FaqItem {
  q: string;
  a: string;
}

export interface WajeezStep {
  n: string;
  t: string;
  d: string;
}

export interface CohortFact {
  label: string;
  value: string;
}

export interface ModeDetail {
  title: string;
  desc: string;
}

export interface StudyModeInfo {
  label: string;
  sub: string;
  items: string[];
  details: ModeDetail[];
  /** schedule line shown beneath the mode card label */
  schedule?: string;
  /** staff card shown beneath the mode card */
  advisor?: {
    name: string;
    role: string;
    phone: string;
    imgSrc: string;
    waLabel: string;
  };
}

export interface GalleryItem {
  src: string;
  alt: string;
}

export interface CorporateInfo {
  photos: string[];
  text: string;
}

export interface MasterclassData {
  slug: string;

  meta: {
    title: string;
    description: string;
  };

  /** hero */
  hero: {
    chip: string;
    h1Line1: string;
    h1GoldLine: string;
    h1Line3?: string;
    desc: string;
    heroBgSrc?: string;         // full-cover bg image (elam, khataba)
    heroCardSrc?: string;       // portrait card image (voice)
    heroCardPosition?: string;
    useSpinningRing?: boolean;  // elam
    stats?: { num: string; label: string }[];
    statsEnabled: boolean;       // false for elam/khataba
    modeChip: string;
    ctaEnroll: string;
    ctaExplore: string;
    ctaExploreHref: string;
    wajeezSubtitle: string;
    audienceTags?: string[];    // elam: 4 tags shown above chip
    factChips?: string[];       // khataba: 3 fact chips shown in cover hero
    ctaEnrollIsWa?: boolean;    // elam: primary CTA opens WhatsApp instead of payment modal
  };

  /** reels — disabled for all three until consent */
  reels: {
    enabled: false;
    urls?: string[];
    badge?: string;
    heading?: string;
    description?: string;
  };

  /** curriculum */
  curriculum: {
    sectionHeading: string;
    sectionHeadingGold: string;
    sectionDesc: string;
    stations: StationItem[];
    phaseBands: PhaseBand[];
    phaseLabels?: Record<number, { label: string; color: string }>;
    /** graduation project card */
    gradProject: {
      title: string;
      desc: string;
      label: string;
      steps: { n: string; t: string; d: string }[];
      outputTitle: string;
      outputText: string;
    };
  };

  portfolio?: {
    /** 'paper' = creamy #F4EFE4 background with dot pattern; default = #F5F4F0 */
    theme?: 'paper';
    badge: string;
    heading: string;
    headingGold: string;
    desc: string;
    tableHeader: string;
    tableCount: string;
    items: PortfolioItem[];
    gradRow: { title: string; kind: string; outputType?: string };
    footerNote: string;
  };

  /** wajeez — absent for elam */
  wajeez?: {
    heading: string;
    headingGold: string;
    desc: string;
    steps: WajeezStep[];
    disclaimer: string;
  };

  /** outcomes */
  outcomes: {
    badge: string;
    heading: string;
    headingGold: string;
    desc: string;
    items: OutcomeItem[];
    /** when true: unnumbered 3-col grid (khataba acquisitions variant) */
    acquisitions?: boolean;
  };

  /** trainers */
  trainers: {
    badge: string;
    heading: string;
    headingGold: string;
    sub: string;
    items: TrainerInfo[];
  };

  /** photo gallery — only khataba */
  gallery?: {
    badge: string;
    heading: string;
    headingGold: string;
    desc: string;
    items: GalleryItem[];
  };

  /** audience — khataba only */
  audience?: {
    badge: string;
    heading: string;
    lead: string;
    items: string[];
  };

  /** learning method — khataba only */
  method?: {
    badge: string;
    heading: string;
    headingGold: string;
    lead: string;
    items: { title: string; body: string }[];
    finalOutput: { title: string; body: string };
  };

  /** study modes */
  modes: {
    badge: string;
    heading: string;
    headingGold: string;
    desc: string;
    inperson: StudyModeInfo;
    online: StudyModeInfo;
  };

  /** pricing */
  pricing: {
    badge: string;
    heading: string;
    headingGold: string;
    cardTitle: string;
    cardDesc: string;
    priceJOD: number;
    priceUSD: number;
    equivalentUSD: number;
    installments: [number, number, number];
    showPerHourLine: boolean;
    features: string[];
    topBadge?: string;
    ctaLabel: string;
    downsellText?: string;
    downsellHref?: string;
    corporate?: CorporateInfo & { heading: string; body: string; cta: string };
  };

  /** advisors */
  advisors: {
    badge: string;
    heading: string;
    headingGold: string;
    sub: string;
    items: AdvisorInfo[];
    footNote?: string;
  };

  /** faq */
  faqs: FaqItem[];

  /** cohort */
  cohort: {
    badge: string;
    startLabel: string;
    startGold: string;
    facts: CohortFact[];
    ctaLabel: string;
    consultNote: string;
    consultHref: string;
  };

  /** payment modal props */
  payment: {
    courseSlug: string;
    courseTitle: string;
    cohortIdOnsite: number;
    cohortIdLive: number;
    cohortStartAr: string;
    cohortDays: string;
    cohortTimeAr: string;
    cohortTrainer: string;
    priceJOD: number;
    priceUSD: number;
  };

  /** wa links */
  wa: {
    phoneOnline: string;
    phoneOnsite?: string;
    phoneCorp?: string;
  };
}

